/**
 * ── حركةُ جدول الأستاذ: متى وقع التغيير، وبأيّ فعل ────────────────────────────
 *
 * سجلُّ الحركة يُبنى من نسخ الجدول المحفوظة، والنسخةُ تُؤخذ **قبل** الفعل الذي
 * تحميه («قبل تعديل موعد دراسي»). فما تغيّر بين نسختين متتاليتين وقع بعد الأولى
 * منهما، بالفعل الذي أُخذت الأولى قبله.
 *
 * وكان التغييرُ يُنسب إلى النسخة الثانية: بوقتها — وقتِ الفعل التالي، أو «الآن»
 * حين تكون الثانيةُ الجدولَ الحاليّ — وباسمها كما هو. فقرأ الأستاذُ في بطاقته
 * «أمن الأنظمة أُضيفت … قبل تعديل موعد دراسي» بوقت تعديلٍ لاحق، و«تغيّر موعدها
 * … الجدول الحالي» بوقت فتحه البطاقة لا بوقت النقل.
 */
export function movementAttribution(before: { at: string; label?: string }): { at: string; label: string } {
  const raw = String(before.label || "").trim();
  /* «قبل X» ⇒ الفعلُ X. وما سواها (توقيعٌ، إرسالٌ، قبول…) لقطاتٌ لا تغيّر شيئاً،
     فالتغييرُ بعدها وقع بمسارٍ لم يسمِّ نفسه: «تعديل الجدول». */
  const act = raw.startsWith("قبل ") ? raw.slice(4).trim() : "";
  return { at: before.at, label: act || "تعديل الجدول" };
}
