const ARABIC_LETTER = "ء-يٱ";

export interface NameCorrection { name: string; rules: string[] }

/** يصحّح اسم مقرر. يردّ الاسم (مصحَّحاً أو كما هو) وقواعد ما غُيّر. */
export function correctCourseName(raw: string): NameCorrection {
  const original = normalize(raw);
  let text = original;
  const rules: string[] = [];
  const apply = (rule: string, next: string) => { if (next !== text) { text = next; if (!rules.includes(rule)) rules.push(rule); } };

  /* 1) تلاصق الكلمات: فراغٌ قبل القوس، وبعد القوس المغلق، وقبل «ال» بعد همزةٍ أو تاءٍ مربوطة. */
  apply("فراغ قبل القوس", text.replace(new RegExp(`([${ARABIC_LETTER}])\\(`, "g"), "$1 ("));
  apply("فراغ بعد القوس", text.replace(new RegExp(`\\)([${ARABIC_LETTER}])`, "g"), ") $1"));
  apply("فصل كلمتين ملتصقتين", text.replace(/([ءئةى])(?=ال[ء-ي]{2,})/g, (_all, ch: string, offset: number) => (offset === 0 ? ch : `${ch} `)));

  /* 2) الهمزة المتطرفة: «ىء» ← «ئ» («مبادىء» ← «مبادئ»). */
  apply("ىء ← ئ", text.replace(/ىء/g, "ئ"));

  /* 3) كلمةً كلمة: الأخطاء المعروفة، فالهمزة على الألف، فالتاء المربوطة، فالياء المنسوبة. */
  const words = text.split(" ").map(word => {
    const lead = word.match(/^[^ء-ي]*/)![0], tail = word.match(/[^ء-ي]*$/)![0];
    const core = word.slice(lead.length, word.length - tail.length);
    if (!core) return word;
    let next = core;
    /* ه ← ة في آخر الكلمة (أربعة أحرفٍ فأكثر، وليست من المستثنيات، ولا ضميراً بعد واو أو ألف). */
    const bare = next.replace(/^(?:وال|بال|فال|كال|لل|ال)/, "");
    if (next.length >= 4 && next.endsWith("ه") && !KEEP_FINAL_HA.has(next) && !KEEP_FINAL_HA.has(bare) && !/[او]ه$/.test(next)) {
      next = `${next.slice(0, -1)}ة`;
      if (!rules.includes("ه ← ة")) rules.push("ه ← ة");
    }
    /* ى ← ي في آخر الكلمة المنسوبة («التعليمى»): بعد «ال» وليست من المستثنيات. */
    if (next.length >= 5 && next.endsWith("ى") && next.startsWith("ال") && !KEEP_FINAL_ALEF_MAQSURA.has(next)) {
      next = `${next.slice(0, -1)}ي`;
      if (!rules.includes("ى ← ي")) rules.push("ى ← ي");
    }
    /* بعد التاء والياء: الأخطاء المطبعية المعروفة، ثم الهمزة على الألف (القاموس مفتاحه الصيغة الصحيحة الرسم). */
    if (TYPO[next] && TYPO[next] !== next) { next = TYPO[next]; if (!rules.includes("خطأ مطبعي معروف")) rules.push("خطأ مطبعي معروف"); }
    if (HAMZA[next] && HAMZA[next] !== next) { next = HAMZA[next]; if (!rules.includes("همزة الألف")) rules.push("همزة الألف"); }
    return `${lead}${next}${tail}`;
  });
  text = words.join(" ");

  return { name: text, rules: text === original ? [] : rules };
}
